"""Normal-regime MYC/APC trajectories, untreated vs ATRA: saved inverse-PINN fit vs Radau.

Reuses the first poster's saved comparison (data/normal_treatment_comparison.npz);
no fitting or simulation is performed here.
"""
import json

import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
import numpy as np

BLUE, ORANGE, INK, GREY = "#1f77b4", "#e88028", "#152a3a", "#7f7f7f"
STATES = [("m", r"MYC $m$", BLUE), ("p", r"APC $p$", ORANGE)]


def make_treatment(data, out, height=3.3):
    d = np.load(data / "normal_treatment_comparison.npz")
    states = d["states"].tolist()
    width = 14.6
    fig, axes = plt.subplots(1, 2, figsize=(width, height), sharey=True)
    fig.subplots_adjust(left=.075, right=.97, bottom=.40, top=.81, wspace=.17)
    for ci, ax in enumerate(axes):
        for state, label, color in STATES:
            k = states.index(state)
            ax.plot(d["t"], d["reference"][ci, :, k], color=color, lw=3.8, alpha=.38)
            ax.plot(d["t"], d["pinn"][ci, :, k], color=color, lw=1.8, ls=(0, (5, 3)))
        ax.set(xlim=(0, 150), ylim=(.20, 1.50), xticks=[0, 50, 100, 150], yticks=[.4, .8, 1.2])
        if ci == 1:
            ax.annotate('', xy=(88, 1.38), xytext=(40, 1.38),
                        arrowprops=dict(arrowstyle='<->', color=INK, lw=1.7))
            ax.text(64, 1.41, 'ATRA', ha='center', va='bottom', fontsize=22, color=INK)
        ax.tick_params(labelsize=22, length=4)
        ax.grid(False)
        ax.spines[["top", "right"]].set_visible(False)
        pos = ax.get_position()
        fig.text(pos.x0, .93, "No treatment" if ci == 0 else "ATRA treatment",
                 fontsize=27, va="center")
    axes[0].set_ylabel("concentration", fontsize=24, labelpad=8)
    fig.text(.535, .215, r"dimensionless time $\tau$", ha="center", va="center", fontsize=23)
    handles = [Line2D([], [], color=c, lw=2.7, label=label) for _, label, c in STATES]
    handles += [Line2D([], [], color=GREY, lw=3, alpha=.5, label="Radau"),
                Line2D([], [], color=INK, lw=1.8, ls=(0, (5, 3)), label="PINN")]
    fig.legend(handles=handles, loc="lower center", bbox_to_anchor=(.535, -.01),
               ncol=len(handles), frameon=False, fontsize=22, handlelength=1.6,
               columnspacing=1.4, handletextpad=.5)
    name = "normal_pinn"
    fig.savefig(out / f"{name}.pdf")
    fig.savefig(out / f"{name}.png", dpi=110)
    plt.close(fig)
    (out / f"{name}-window.tex").write_text(
        "% Generated by figures/treatment_plot.py; the ATRA arrow is drawn in the PDF.\n"
        rf"\includegraphics[width=14.6in]{{assets/{name}.pdf}}" + "\n")
    (out / f"{name}_audit.json").write_text(json.dumps({
        "condition_order": d["conditions"].tolist(), "DR": d["DR"].tolist(),
        "states": [s for s, _, _ in STATES], "normal_only": True, "height_in": height,
        "ATRA_arrow": {"tau": [40, 88], "y": 1.38, "panel": "ATRA treatment"}}, indent=2) + "\n")
